  // Get current language from storage or browser
  function getCurrentLanguage() {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored && translations[stored]) {
        return stored;
      }
    } catch (e) {
      console.warn('Failed to read language preference:', e);
    }
    
    // Try to detect browser language
    const browserLang = navigator.language || navigator.userLanguage;
    if (browserLang) {
      const langCode = browserLang.split('-')[0].toLowerCase();
      if (translations[langCode]) {
        return langCode;
      }
    }
    
    return DEFAULT_LANGUAGE;
  }

  // Save language preference
  function setLanguage(langCode) {
    if (!translations[langCode]) {
      console.warn(`Language ${langCode} not supported`);
      return false;
    }
    
    try {
      localStorage.setItem(STORAGE_KEY, langCode);
      currentLanguage = langCode;
      
      // Update HTML lang attribute
      document.documentElement.lang = langCode;
      
      // Trigger language change event
      const event = new CustomEvent('languageChanged', { detail: { language: langCode } });
      document.dispatchEvent(event);
      
      return true;
    } catch (e) {
      console.error('Failed to save language preference:', e);
      return false;
    }
  }

  // Get translation for a key
  function t(key, fallback = null) {
    const lang = currentLanguage;
    if (translations[lang] && translations[lang][key]) {
      return translations[lang][key];
    }
    
    // Fallback to English
    if (lang !== DEFAULT_LANGUAGE && translations[DEFAULT_LANGUAGE] && translations[DEFAULT_LANGUAGE][key]) {
      return translations[DEFAULT_LANGUAGE][key];
    }
    
    return fallback !== null ? fallback : key;
  }

  // Translate all elements with data-i18n attribute
  function translatePage() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(element => {
      const key = element.getAttribute('data-i18n');
      const translation = t(key);
      
      if (translation) {
        // Handle different element types
        if (element.tagName === 'INPUT' && element.type === 'submit') {
          element.value = translation;
        } else if (element.tagName === 'INPUT' && element.placeholder !== undefined) {
          const placeholderKey = element.getAttribute('data-i18n-placeholder');
          if (placeholderKey) {
            element.placeholder = t(placeholderKey);
          }
        } else if (element.hasAttribute('data-i18n-html')) {
          element.innerHTML = translation;
        } else {
          element.textContent = translation;
        }
      }
    });
    
    // Update title if it has data-i18n-title
    const titleElement = document.querySelector('[data-i18n-title]');
    if (titleElement) {
      const titleKey = titleElement.getAttribute('data-i18n-title');
      if (titleKey) {
        document.title = t(titleKey);
      }
    }
  }

  // Initialize
  let currentLanguage = getCurrentLanguage();
  setLanguage(currentLanguage); // This will set the HTML lang attribute

  // Auto-translate on page load
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', translatePage);
  } else {
    translatePage();
  }

  // Re-translate when language changes
  document.addEventListener('languageChanged', translatePage);

  // Export to window
  window.i18n = {
    getLanguage: () => currentLanguage,
    setLanguage: setLanguage,
    t: t,
    translate: translatePage,
    getSupportedLanguages: () => Object.keys(SUPPORTED_LANGUAGES).map(code => ({
      code,
      ...SUPPORTED_LANGUAGES[code]
    })),
    getSupportedLanguagesObject: () => SUPPORTED_LANGUAGES
  };
